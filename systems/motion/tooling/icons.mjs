// Build the DS icon set from open-source Lucide icons (lucide-static, ISC; see
// systems/motion/registry/LICENSES/lucide.txt). Names are ours (systems/motion/tooling/icon-map.json maps each
// to a Lucide icon); no captured app artwork ships in the package.
// Output: systems/motion/registry/src/icons/paths.ts
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');

const LUCIDE = path.join(ROOT, 'node_modules/lucide-static');
const map = JSON.parse(await fs.readFile(path.join(ROOT, 'systems/motion/tooling/icon-map.json'), 'utf8'));
const { version } = JSON.parse(await fs.readFile(path.join(LUCIDE, 'package.json'), 'utf8'));

const defaultSize = (name) => {
  const at = name.match(/@([\d.]+)$/);
  if (at) return Number(at[1]);
  return /Small$/.test(name) ? 16 : 20;
};

const entries = {};
const missing = [];
for (const [name, value] of Object.entries(map)) {
  if (name.startsWith('$')) continue;
  const spec = typeof value === 'string' ? { lucide: value } : value;
  let src;
  try {
    src = await fs.readFile(path.join(LUCIDE, 'icons', `${spec.lucide}.svg`), 'utf8');
  } catch {
    missing.push(`${name} -> ${spec.lucide}`);
    continue;
  }
  let inner = src.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/\s*\/>/g, ' />').replace(/\s+/g, ' ').replace(/> </g, '><').trim();
  if (spec.fill) inner = `<g fill="currentColor">${inner}</g>`;
  entries[name] = { size: spec.size ?? defaultSize(name), svg: inner, lucide: spec.lucide };
}
if (missing.length) {
  console.error(`Missing Lucide icons:\n  ${missing.join('\n  ')}`);
  process.exit(1);
}

const names = Object.keys(entries).sort();
const body = names.map((n) => `  ${JSON.stringify(n)}: { viewBox: "0 0 24 24", size: ${entries[n].size}, svg: ${JSON.stringify(entries[n].svg)} }, // ${entries[n].lucide}`).join('\n');
const ts = `// Generated by systems/motion/tooling/icons.mjs from Lucide (lucide-static@${version}, ISC License,
// see LICENSES/lucide.txt). Mapping: systems/motion/tooling/icon-map.json. Do not edit by hand.
// ${names.length} icons. Stroked 24x24 drawings; \`size\` is the default rendered px.
export const iconPaths = {
${body}
} as const;

export type IconName = keyof typeof iconPaths;
`;
await fs.writeFile(path.join(ROOT, 'systems/motion/registry/src/icons/paths.ts'), ts);
console.log(`${names.length} icons written`);
