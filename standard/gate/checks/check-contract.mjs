// Contract check: does the system export every inventory entry with props that accept the contract?
// Generates a TypeScript file that assigns each contract props type to the system component's props
// (and, for hooks, the system's return value to the contract API), then type-checks it.
// Usage: node standard/gate/checks/check-contract.mjs [system=motion]
import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import { build } from 'esbuild';

const system = process.argv[2] ?? 'motion';
const root = path.resolve('.');
const src = path.join(root, 'systems', system, 'registry', 'src', 'index.ts');
const tmp = path.join(root, '.scratch', 'gate', system, 'contract');
await fs.mkdir(tmp, { recursive: true });

const invFile = path.join(tmp, 'inventory.mjs');
await build({ entryPoints: [path.join(root, 'standard/contract/src/inventory.ts')], bundle: true, format: 'esm', platform: 'node', outfile: invFile, logLevel: 'error' });
const { inventory } = await import(`${invFile}?t=${Date.now()}`);

const rel = (p) => path.relative(tmp, p).replace(/\\/g, '/').replace(/\.ts$/, '');
const lines = [
  `// Generated by check-contract.mjs. Each line fails to compile if the system breaks the contract.`,
  `import type { ComponentProps } from 'react';`,
  `import * as S from '${rel(src)}';`,
  `import type * as C from '${rel(path.join(root, 'standard/contract/src/index.ts'))}';`,
  ``,
];
for (const e of inventory) {
  const id = e.name;
  if (e.kind === 'hook') {
    lines.push(`export const ${id}_returns: (api: ReturnType<typeof S.${id}>) => C.${e.contract} = (api) => api;`);
  } else if (e.kind === 'compound') {
    for (const part of e.parts) {
      lines.push(`export const ${id}_${part}: (p: C.${e.contract}['${part}']) => ComponentProps<typeof S.${id}.${part}> = (p) => p;`);
    }
  } else {
    lines.push(`export const ${id}_props: (p: C.${e.contract}) => ComponentProps<typeof S.${id}> = (p) => p;`);
  }
}
await fs.writeFile(path.join(tmp, 'contract-check.ts'), lines.join('\n') + '\n');
await fs.writeFile(path.join(tmp, 'tsconfig.json'), JSON.stringify({
  compilerOptions: { target: 'ES2022', module: 'ESNext', moduleResolution: 'Bundler', jsx: 'react-jsx', strict: true, noEmit: true, skipLibCheck: true, isolatedModules: true, lib: ['ES2022', 'DOM', 'DOM.Iterable'], types: [] },
  files: ['contract-check.ts'],
}, null, 1));

let out = '';
try {
  execFileSync(path.join(root, 'node_modules/.bin/tsc'), ['-p', path.join(tmp, 'tsconfig.json')], { encoding: 'utf8', stdio: 'pipe' });
} catch (e) {
  out = (e.stdout || '') + (e.stderr || '');
}
// Only errors in the generated file are contract failures; group them by inventory entry.
const failures = new Map();
const genLines = lines;
for (const m of out.matchAll(/contract-check\.ts\((\d+),\d+\): error (TS\d+): ([\s\S]*?)(?=\n\S|$)/g)) {
  const line = genLines[Number(m[1]) - 1] ?? '';
  const name = line.match(/export const (\w+?)_/)?.[1] ?? '?';
  const what = line.match(/export const (\w+)/)?.[1] ?? '?';
  const msg = m[3].split('\n').map((s) => s.trim()).filter(Boolean).slice(0, 3).join(' / ');
  if (!failures.has(name)) failures.set(name, []);
  failures.get(name).push(`${what}: ${msg}`);
}
// Flat aliases (MenuItem…) are generated by the build; check them in the built types.
const dts = await fs.readFile(path.join(root, 'systems', system, 'registry', 'dist', 'client.d.ts'), 'utf8').catch(() => null);
if (dts) {
  for (const e of inventory.filter((x) => x.kind === 'compound')) {
    const missing = e.parts.filter((p) => !new RegExp(`export (declare )?(const|function) ${e.name}${p}\\b`).test(dts) && !new RegExp(`\\b${e.name}${p}\\b`).test(dts.match(/export \{[^}]*\}/g)?.join(' ') ?? ''));
    if (missing.length) {
      if (!failures.has(e.name)) failures.set(e.name, []);
      failures.get(e.name).push(`flat aliases missing in dist (rebuild?): ${missing.map((p) => e.name + p).join(', ')}`);
    }
  }
}
const otherErrors = out.split('\n').filter((l) => /error TS/.test(l) && !l.includes('contract-check.ts'));

const report = { system, entries: inventory.length, failing: [...failures.keys()], failures: Object.fromEntries(failures), otherErrors: otherErrors.length };
await fs.writeFile(path.join(tmp, 'report.json'), JSON.stringify(report, null, 1));
console.log(`contract: ${inventory.length - failures.size}/${inventory.length} inventory entries conform`);
for (const [name, msgs] of failures) {
  console.log(`✗ ${name}`);
  for (const m of msgs.slice(0, 4)) console.log(`    ${m.slice(0, 300)}`);
}
if (otherErrors.length) console.log(`(${otherErrors.length} type errors inside the system source itself; run the system typecheck)`);
process.exit(failures.size ? 1 : 0);
